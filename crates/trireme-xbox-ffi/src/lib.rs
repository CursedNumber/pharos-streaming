//! C-ABI shim for the Xbox (UWP) client shell.
//!
//! The shared Rust core does not decode, render, or play audio: it hands the
//! shell raw HEVC/AV1 access units and Opus packets, and forwards the shell's
//! gamepad back to the host. On Android that boundary is UniFFI/Kotlin; on iOS
//! it is UniFFI/Swift; here it is a hand-written C ABI that a C++/WinRT UWP app
//! links against. This file is a thin adapter: it wraps C function pointers in
//! [`core_ffi::FrameSink`] / [`core_ffi::AudioSink`] implementations and calls
//! the same [`core_ffi::start_video_stream`] / [`core_ffi::client_pair`] every
//! other client uses.
//!
//! Header: generated by cbindgen (`cbindgen --config cbindgen.toml --crate
//! trireme-xbox-ffi --output trireme_xbox.h`); see README.
//!
//! Threading: `start` returns immediately; the QUIC client runs on its own
//! thread inside the core. The frame/audio callbacks fire from that thread, so
//! the shell must marshal to its render/audio threads and MUST NOT block (the
//! callbacks run on the QUIC loop). Every input call is cheap and non-blocking.

#![allow(clippy::missing_safety_doc)]

use core_ffi::{
    client_pair, start_video_stream, AudioSink, FrameSink, GamepadInput, PairError, StreamMode,
};
use std::ffi::{c_char, c_int, c_void, CStr};
use std::sync::Arc;

// --- Callback types the shell provides ------------------------------------

/// One compressed video access unit (HEVC or AV1). Feed to the Media Foundation
/// decoder MFT. `data` is valid only for the duration of the call.
pub type FrameCallback = extern "C" fn(ctx: *mut c_void, data: *const u8, len: usize);
/// One Opus packet (48 kHz / stereo / 20 ms). Decode + play; never block.
pub type AudioCallback = extern "C" fn(ctx: *mut c_void, data: *const u8, len: usize);
/// Stream ended. `error` is NUL-terminated UTF-8, or null for a clean close.
pub type EndCallback = extern "C" fn(ctx: *mut c_void, error: *const c_char);
/// Host link-health heartbeat (~2x/s): `true` while the host is shedding video.
pub type LinkHealthCallback = extern "C" fn(ctx: *mut c_void, degraded: bool);

// --- FrameSink / AudioSink adapters ---------------------------------------

struct CFrameSink {
    ctx: *mut c_void,
    on_frame: FrameCallback,
    on_end: EndCallback,
    on_link_health: LinkHealthCallback,
}
// The shell guarantees `ctx` is safe to touch from the QUIC thread (it hands us
// a pointer to its own thread-safe player state).
unsafe impl Send for CFrameSink {}
unsafe impl Sync for CFrameSink {}

impl FrameSink for CFrameSink {
    fn on_frame(&self, data: Vec<u8>) {
        (self.on_frame)(self.ctx, data.as_ptr(), data.len());
    }
    fn on_end(&self, error: Option<String>) {
        match error {
            Some(e) => {
                let c = std::ffi::CString::new(e).unwrap_or_default();
                (self.on_end)(self.ctx, c.as_ptr());
            }
            None => (self.on_end)(self.ctx, std::ptr::null()),
        }
    }
    fn on_link_health(&self, degraded: bool) {
        (self.on_link_health)(self.ctx, degraded);
    }
}

struct CAudioSink {
    ctx: *mut c_void,
    on_packet: AudioCallback,
}
unsafe impl Send for CAudioSink {}
unsafe impl Sync for CAudioSink {}

impl AudioSink for CAudioSink {
    fn on_packet(&self, opus: Vec<u8>) {
        (self.on_packet)(self.ctx, opus.as_ptr(), opus.len());
    }
}

// --- Opaque stream handle -------------------------------------------------

/// Opaque handle returned by [`trireme_start`]; holds the client→host input
/// channel. Free it exactly once with [`trireme_stop`].
pub struct TriremeStream {
    gp: Arc<GamepadInput>,
}

// --- Small helpers --------------------------------------------------------

unsafe fn cstr_opt(p: *const c_char) -> Option<String> {
    if p.is_null() {
        return None;
    }
    match CStr::from_ptr(p).to_str() {
        Ok(s) if !s.is_empty() => Some(s.to_owned()),
        _ => None,
    }
}

unsafe fn cstr_req(p: *const c_char) -> String {
    if p.is_null() {
        return String::new();
    }
    CStr::from_ptr(p).to_string_lossy().into_owned()
}

// --- Lifecycle / hello ----------------------------------------------------

/// Install the core's `tracing` subscriber. `level` is a RUST_LOG-style filter
/// (e.g. "info", "info,transport=debug") or null for the default. On Xbox this
/// goes to stderr, visible in the Visual Studio remote debugger's output.
#[no_mangle]
pub unsafe extern "C" fn trireme_init_logging(level: *const c_char) {
    core_ffi::init_logging(cstr_opt(level).unwrap_or_else(|| "info".to_string()));
}

/// The "hello core" round-trip target for Phase 0: proves the UWP-target static
/// lib links and runs. Returns the wire protocol version the core speaks.
#[no_mangle]
pub extern "C" fn trireme_protocol_version() -> u32 {
    core_ffi::core_info().protocol_version
}

// --- Pairing (Phase 1) ----------------------------------------------------

/// Drive one SPAKE2 pairing attempt against a Pharos host. Blocks the caller,
/// so the shell should call it off the UI thread. On success writes the host's
/// 64-char hex pubkey (NUL-terminated) into `out_pubkey_hex` (capacity
/// `out_cap`, 65+ recommended) and returns 0. On failure returns a negative
/// code: -1 bad address, -2 identity, -3 network, -4 protocol, -5 PIN/identity
/// mismatch, -6 host aborted.
#[no_mangle]
pub unsafe extern "C" fn trireme_pair(
    addr: *const c_char,
    pin: *const c_char,
    identity_path: *const c_char,
    out_pubkey_hex: *mut c_char,
    out_cap: usize,
) -> c_int {
    let addr = cstr_req(addr);
    let pin = cstr_req(pin);
    let id_path = cstr_req(identity_path);
    match client_pair(addr, Vec::new(), pin, id_path, None) {
        Ok(res) => {
            if !out_pubkey_hex.is_null() && out_cap > 0 {
                let bytes = res.host_pubkey_hex.as_bytes();
                let n = bytes.len().min(out_cap - 1);
                std::ptr::copy_nonoverlapping(bytes.as_ptr(), out_pubkey_hex as *mut u8, n);
                *out_pubkey_hex.add(n) = 0;
            }
            0
        }
        Err(e) => pair_error_code(&e),
    }
}

fn pair_error_code(e: &PairError) -> c_int {
    match e {
        PairError::BadAddress { .. } => -1,
        PairError::Identity { .. } => -2,
        PairError::Network { .. } => -3,
        PairError::Protocol { .. } => -4,
        PairError::PinMismatch => -5,
        PairError::HostAborted { .. } => -6,
    }
}

// --- Streaming (Phases 2-5) -----------------------------------------------

/// Connect to a Pharos streamer and deliver access units to the callbacks.
/// Returns a handle (null on bad UTF-8 in `addr`). `pubkey_hex` null/empty =
/// TOFU; `identity_path` null = anonymous. Pass `on_audio` null to drop audio.
///
/// `on_audio` is spelled as an inline `Option<extern "C" fn>` rather than
/// `Option<AudioCallback>`: cbindgen can't see through an Option-of-alias (it
/// emits an opaque by-value `Option_AudioCallback` struct and drops the
/// `AudioCallback` typedef, which doesn't compile), while the inline form
/// renders as the intended nullable C function pointer. ABI-identical either
/// way (guaranteed niche optimization for `Option<fn>`).
#[no_mangle]
pub unsafe extern "C" fn trireme_start(
    addr: *const c_char,
    pubkey_hex: *const c_char,
    identity_path: *const c_char,
    width: u32,
    height: u32,
    refresh_mhz: u32,
    frame_ctx: *mut c_void,
    on_frame: FrameCallback,
    on_end: EndCallback,
    on_link_health: LinkHealthCallback,
    audio_ctx: *mut c_void,
    on_audio: Option<extern "C" fn(ctx: *mut c_void, data: *const u8, len: usize)>,
) -> *mut TriremeStream {
    let addr = cstr_req(addr);
    if addr.is_empty() {
        return std::ptr::null_mut();
    }

    let frame_sink: Box<dyn FrameSink> = Box::new(CFrameSink {
        ctx: frame_ctx,
        on_frame,
        on_end,
        on_link_health,
    });
    let audio_sink: Option<Box<dyn AudioSink>> = on_audio.map(|cb| {
        Box::new(CAudioSink {
            ctx: audio_ctx,
            on_packet: cb,
        }) as Box<dyn AudioSink>
    });

    let gp = start_video_stream(
        addr,
        Vec::new(),              // alt_addrs: shell does mDNS/failover itself
        cstr_opt(pubkey_hex),    // expected host pubkey, or TOFU
        cstr_opt(identity_path), // identity.toml path, or anonymous
        frame_sink,
        audio_sink,
        None, // gyro_sink   (Xbox pads have no IMU relay yet)
        None, // app_catalog (Phase 6)
        None, // clipboard   (Phase 6)
        false,
        StreamMode {
            width,
            height,
            refresh_mhz,
        },
    );

    Box::into_raw(Box::new(TriremeStream { gp }))
}

/// Stop the stream and free the handle. Safe on null; call exactly once.
#[no_mangle]
pub unsafe extern "C" fn trireme_stop(h: *mut TriremeStream) {
    if h.is_null() {
        return;
    }
    let s = Box::from_raw(h);
    s.gp.stop();
}

/// Ask the host for a fresh keyframe (call when the decoder reports corruption).
#[no_mangle]
pub unsafe extern "C" fn trireme_request_idr(h: *mut TriremeStream) {
    if let Some(s) = h.as_ref() {
        s.gp.request_keyframe();
    }
}

// --- Input (Phase 3) ------------------------------------------------------
//
// Map Windows.Gaming.Input into the canonical index space (core_proto::gamepad)
// on the shell side, then call these. All are cheap, non-blocking, no-op after
// the stream ends.

/// A controller appeared on `slot`; the host brings up a virtual pad.
#[no_mangle]
pub unsafe extern "C" fn trireme_pad_connect(
    h: *mut TriremeStream,
    slot: u8,
    vendor: u16,
    product: u16,
) {
    if let Some(s) = h.as_ref() {
        s.gp.connect(slot, vendor, product);
    }
}

/// A controller on `slot` went away.
#[no_mangle]
pub unsafe extern "C" fn trireme_pad_disconnect(h: *mut TriremeStream, slot: u8) {
    if let Some(s) = h.as_ref() {
        s.gp.disconnect(slot);
    }
}

/// Canonical gamepad button up/down.
#[no_mangle]
pub unsafe extern "C" fn trireme_pad_button(
    h: *mut TriremeStream,
    slot: u8,
    button: u8,
    pressed: bool,
) {
    if let Some(s) = h.as_ref() {
        s.gp.button(slot, button, pressed);
    }
}

